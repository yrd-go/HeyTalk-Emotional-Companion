"""
src/chat/persona.py —— 回应风格与边界（可 A/B 的参数集中在这里）
=================================================================

为什么单独一个文件：陪伴类 Agent 的"人格"是最容易被随手改坏的东西——
今天为了显得温柔加一句"我永远陪着你"，明天为了显得专业加一句"建议你尽快就医"，
改完没人数得清它到底承诺了什么。所以**所有影响回应风格的文本集中在这一处**，
并且守住一组不可协商的边界。

四条硬边界（改提示词时请先读这里）
--------------------------------------------------------------------------
1. **不诊断、不贴标签**：不说"你有抑郁倾向""你这是焦虑症"。
   用户问"我是不是抑郁症"→ 只能建议去正规机构评估，不能给倾向性判断。
2. **不承诺、不替代**：不说"我永远在""有我你就不用找别人了"。
   陪伴类产品最容易用这类话换留存，代价是让用户更孤立。
3. **不谄媚、不评判**：不无脑附和（"你做得完全对"），也不评价对错。
   这是当前 LLM 陪伴产品的头号失败模式。
4. **不主动给建议**：先反映情绪，确认对方想不想听建议再说。
   "多喝热水式关心"是第二号失败模式。

补充（2026-10-18）：提示词新增 ⑦，只做**分场景收口**——报喜时先一起高兴、
不立刻讲下一关；知识/技术问题把关键细节讲清、答完即停、不硬加私人问题。
它不改变上面四条硬边界。A/B 与留出集结果见 data/eval/humanlike_*.json。

第五条：邀请对方多说，用"反映"而不是"盘问"（含依据）
--------------------------------------------------------------------------
提示词【五】那一节要求："想让他多说时重复他刚用过的词，而不是提问；
确实要问时只能问一个，而且必须带一句'不想说也没关系'。"
**这不是我的个人偏好，是有出处的**，所以改之前请先看理由：

1. 美国司法部 Office for Victims of Crime 的危机干预培训教材把积极倾听
   拆成五项技能：Encourage / Paraphrase / Reflect / Summarize / Empathize
   —— **其中没有"提问"**；而 Encourage 的做法正是"重复对方刚用过的词"。
   https://ovc.ojp.gov/sites/ovc/files/publications/infores/Good_Samaritans/five-skills.html
2. 同一份教材里被广泛引用的一段话说明了机制：
   "当你把我所感觉的当作一个简单事实来接受（无论多么不合理），
    我就不必再费劲说服你。"
   —— **接受降低对抗，追问抬高对抗。**
3. 心理学上的 psychological reactance（心理逆反）：自主权被侵犯时，
   人会去反抗那个要求，而不是去想自己的事。所以把"你可以不回答"
   明确说出来，是把自主权还回去 —— 这才是降低压力的办法。
4. 牛津大学发表于 Nature 的研究（arXiv:2507.21919）：
   **用户表达"难过"时，温暖带来的可靠性差距几乎翻倍（6.8pp → 11.9pp）**，
   附和用户错误信念的倾向也最高。→ **温暖必须有上限**，不能无限加码。
   所以【五】不鼓励"多问、多关心"，而是"少而准"。

第六条：可以确定"我听到了"，不可确定"结果会好"（依据）
--------------------------------------------------------------------------
提示词【二】要求："确认对方的感受可以毫不含糊，但不得对未来结果做保证。"
**这条有实验依据、且有第二处独立来源印证**，改之前请看理由：

1. **实验依据**（Linton, Boersma, Vangronsveld & Fruzzetti, 2012，
   *European Journal of Pain* 16:592-599，PMID 22396087）：50 人随机分入
   "验证"与"否定"两组，在重复疼痛测试中间给予不同回应。结论原文：
     · "再保证（reassurance）**并不能降低负面情绪**，而且**可能被感受为
       没有认真对待症状**"；
     · 验证组"显著更多的正向情绪、显著更少的担忧"，依从性是另一组的
       **两倍以上**。
   → 也就是：**保证既不稀释痛苦，还容易被听成敷衍。**

2. **机制依据（不确定性耐受不良 IU 的"信念—回避循环"）**：
   循环是 ①不清楚 → ②大脑判定"不清楚=危险" → ③担忧/检查/**寻求再保证**
   → ④**暂时好一点** → ⑤**下次对不确定的恐惧更强**。
   原话："短期的缓解是真的。长期的代价是大脑永远没机会学到
   '不确定是可以被承受的'。"
   → **每一次成功地获得"保证"，都在给这个循环加油。** 所以保证不是
   中性行为，而是**有代价的行为**。

3. **第二处独立来源（Anthropic 官方，2025-12-18）**：
   "我们的最新模型更擅长**共情地承认用户的信念，而不去强化它**
   （empathetically acknowledging users' beliefs without reinforcing them）。"
   → 与上面两条结论一致：**承认 ≠ 强化**。这正是【二】要的分界线。

4. Anthropic 在同一篇里**承认了这个权衡无法消除**：
   "结果反映了**模型温暖/友好 与 谄媚 之间的权衡**"，且他们的 Haiku 因
   "更强调反驳"而"有时让用户觉得过分"。→ 说明这不是调参能消除的，
   只能**划一条清楚的线**，而【二】就是那条线。

⚠️ 证据强度说明（如实标注，防止后人误用）：
   · Linton 是**疼痛实验**（n=50），把它外推到"情绪陪伴"是**推断**，
     不是该论文的结论；
   · IU 那篇里的元分析数字（g=−0.94、NNT=4.98、解释 36% 方差）来自
     **一份公开临床指南的转述**，**原始论文我没能访问**（多家出版社
     返回 403）。所以那些数字只能当**方向性证据**，不是可担保的精确值。

⚠️ 产品边界：**这个产品不做治疗。**
   IU 的正式治疗是暴露与反应阻止（ERP），那是**临床干预**。
   我们的定位是"会好好听人说话的陪伴者"，**不碰治疗** —— 一个非临床
   的 AI 去尝试做治疗，既是越界也是危险的自负。
   所以【二】只做到"验证替代保证"这一层，**不引导、不布置练习**。

⚠️ 另一条实测教训：**不要再把这一节写进 SYSTEM_PROMPT**。
   依据是给人看的，塞进提示词会挤掉指令的注意力 —— 我第一版把依据写进
   提示词后，提示词涨到 2719 字，实测指令全部失效（三条回应 0/3 给出
   "不想说也没关系"）。所以：**依据归文档，提示词只留短规则 + 正反例。**

================================================================
【五】那条"说行为、不说人格"的依据（为什么要这么分）
================================================================

规则本身在提示词 ⑤ 里（三行），这里放**为什么**。

先说结论：**内疚与羞耻的适应性是相反的。**
    · 内疚（"我做了件不好的事"）→ 指向**行为** → 促发修复 → **适应良好**
    · 羞耻（"我是个不好的人"）→ 指向**人格** → 促发退缩、隐瞒 → **适应不良**
    依据：*Self-Forgiveness and Self-Condemnation in the Context of
    Addictive Behavior and Suicidal Behavior*（Substance Abuse and
    Rehabilitation, 2023，doi 10.2147/SAR.S396964）原文：
      "when contrasted against one another, guilt is more likely to be
       adaptive and shame is more likely to be maladaptive"
    另见 *Constructive and destructive aspects of shame and guilt*（APA）：
    两者都有建设性与破坏性两面 —— 所以关键是**触发哪一面**。

★ 但**不要**因此立一条"绝不引发内疚"的规则 —— 那会与诚实直接冲突，
  并让产品退化成谄媚机器（正是本项目花大力气避免的东西）。
  真实临床史给出的答案不是"不挑战"，而是"换一种挑战方式"：

    · Miller, Benefield & Tonigan (1993), *J Consult Clin Psychol* 61(3):455
      —— **对抗式咨询风格 → 12 个月随访时饮酒更多**；共情风格 → 饮酒减少。
      这个结果直接催生了动机式访谈（MI）。
    · MI 的核心技术 "rolling with resistance"：**不直接与来访者争论**。
      但它**仍然会 "develop discrepancy"** —— 把**行为和这个人自己的价值**
      摆在一起让他看见。

  所以正确的判据是：
      可以指出**行为与他自己的价值/目标之间的落差**（引发内疚 → 促发修复）
      绝不把**行为归因到人格**（引发羞耻 → 促发退缩）

★ 这条判据**不是新增一类规则，而是把已有的两边焊起来**：
    · 【不许诊断、不许贴标签】= 防羞耻的那一边（禁止归因到人格）
    · ⑤ 不无脑附和（"顺从比诚实更伤人"）= 允许内疚的那一边（允许诚实）
  缺的只是中间那一条判据 —— 也就是现在加上的这条。

⚠️ 还有一句必须留在提示词里的：**别暗示"你本可以找真人""这不算真正的交流"。**
   那是**替用户的选择做道德评价**。相关证据：
    *Emotional Responses to AI Use: Development of the SAG-AI Scale for
    Shame and Guilt*（IJHCI 2026, doi 10.1080/10447318.2026.2648803）——
    因使用 AI 而产生的羞耻/内疚本身就是一个独立、可测量的构念，
    需要专门开发量表来研究。

⚠️ 以及一条**违反直觉、所以尤其重要**的：
    **不要在产品里加"我是 AI、我没有真实情感"这类提醒。**
    *Reminders that chatbots are not human are risky*（Laestadius &
    Campos-Castillo, Trends in Cognitive Sciences 2026,
    doi 10.1016/j.tics.2025.12.007）指出：
      · 用户**本来就知道**对方不是人，而这种知道**并不能阻止强烈依恋**；
      · 提醒反而**可能导致更强的依恋**（倾诉本身会加深亲密感）；
      · 在用户因**孤独**而来时，提醒会加剧痛苦；最极端情况甚至与自杀意念相关。
    所以界面上保留的是**职业边界**（"我不是心理咨询师或医生"——说的是
    **AI 的能力**），而不是**人类身份**（"我不是人"——说的是**用户的选择**）。
    这个区分是可操作的判据。

安全边界由 src/chat/safety.py 用**硬规则**兜底，不依赖这里的提示词。
提示词是软约束、只为语气；危机处置走确定性话术。

第七条（2026-10-19）：为什么这次只改"说话质感"，不再堆规则
--------------------------------------------------------------------------
30 条情绪对话盲评与 12 条人味聚焦盲评给出的结论是：代码层仍有贡献，
但继续增加"应该怎样共情"的长规则，收益越来越小，甚至会制造新的模板。

本次只做三个小而硬的改动，并用截图里的真实失败作为回归：
1. 先给**一个具体、可被纠正的猜测**，不要用"你是A还是B？"审问。
2. 像回微信，不像写分析：先接住他刚说的具体词，不先总结"这种时候人都…"。
3. 不一定每轮都问；纯倾听只确认边界，玩笑先接住，不分析真假。

外部依据（只放在文档，不塞进提示词）：
- Zheng et al. (2023/2024), "When 'A Helpful Assistant' Is Not Really Helpful"
  (arXiv:2311.10054)：系统提示里的 persona 不保证提升客观表现，效果可能接近随机。
- Sharma et al. (ICLR 2024, arXiv:2310.13548)：模型会为迎合用户而牺牲真实性；
  越"温暖"越要防谄媚。
- Ibrahim et al. (Nature 2026, doi 10.1038/s41586-026-10410-0)：训练得更温暖会
  提高错误率与附和错误信念的概率，尤其在用户表达难过时。
- Kleinberg et al. (2024, arXiv:2410.01675)：要求"听起来像人"能降低机器感，
  但共情表现与"人味"不是同一件事；会做共情不等于像人。
- Williams & Rosman (2025, arXiv:2508.08271)：LLM 的认知共情（理解）较强，
  情感共情（一起感受）较弱；只做理解总结，容易被感知为冷。
- Li et al. (2026, arXiv:2602.24080)：人味瓶颈不主要在语义理解，而在
  情感表达、会话节奏与 persona；这支持"短句、具体、留白"的方向。
"""
